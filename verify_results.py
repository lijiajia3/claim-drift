#!/usr/bin/env python3
"""Compare relocated saved-input calculations with the published numerical tables."""
from __future__ import annotations
import argparse
import csv
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parent
GROUPS = {
    "scores": ("data/core/outputs", "results/scores"),
    "literal": ("data/literal/outputs", "results/literal"),
    "selection": ("data/selection/reference_outputs", "results/selection"),
    "retention": ("data/retention/reported_results", "results/retention"),
}

def read(path):
    with path.open(encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        return reader.fieldnames, list(reader)

def check_csv(reference, actual):
    fields, expected = read(reference)
    got_fields, got = read(actual)
    assert fields == got_fields, f"Columns differ: {actual}"
    assert len(expected) == len(got), f"Row count differs: {actual}"
    for i, (left, right) in enumerate(zip(expected, got)):
        for field in fields:
            x, y = left[field], right[field]
            if x == y:
                continue
            if x.lstrip("-").isdigit() and y.lstrip("-").isdigit():
                assert int(x) == int(y), (actual.name, i, field, x, y)
                continue
            try:
                a, b = float(x), float(y)
            except (ValueError, TypeError):
                raise AssertionError(f"Text differs: {actual.name}, row {i}, {field}")
            assert np.isclose(a, b, atol=1e-12, rtol=1e-12, equal_nan=True), (
                actual.name, i, field, a, b)
    return len(got)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=(*GROUPS, "external"))
    parser.add_argument("--strict-bytes", action="store_true")
    args = parser.parse_args()
    if not args.only or args.only == "selection":
        # The original formatter supplies the published rounded editorial table.
        import subprocess, sys
        subprocess.run([sys.executable, str(ROOT / "tools/make_selection_report.py")],
                       cwd=ROOT, check=True)
    report = []
    for group, (ref_dir, result_dir) in GROUPS.items():
        if args.only and args.only != group:
            continue
        for ref in sorted((ROOT / ref_dir).glob("*.csv")):
            if group == "scores" and ref.name == "event_group_plot_data.csv":
                # Auxiliary figure-builder output; not generated by these entry points.
                continue
            if group == "retention" and ref.name not in {
                "benchmark_results.csv", "benchmark_support.csv", "source_results.csv",
                "project_concentration.csv", "strata_pattern_counts.csv", "monte_carlo_checks.csv"}:
                continue
            actual = ROOT / result_dir / ref.name
            assert actual.is_file(), f"Missing reproduction output: {actual}"
            rows = check_csv(ref, actual)
            if group == "retention" and args.strict_bytes:
                assert ref.read_bytes() == actual.read_bytes(), f"Byte mismatch: {actual}"
            report.append({"analysis": group, "file": ref.name, "rows": rows,
                           "numerical_match": True})
    if not args.only or args.only == "external":
        # This standard-library entry point asserts all published audit counts.
        import subprocess, sys
        subprocess.run([sys.executable, str(ROOT / "reproduce_external_linkage.py")],
                       cwd=ROOT, check=True)
    out = ROOT / "results" / ("verification.json" if not args.only else f"verification_{args.only}.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"status": "passed", "numeric_tolerance": 1e-12,
                              "checks": report}, indent=2) + "\n")
    print(f"PASS: {len(report)} published CSV tables matched; receipt: {out.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
